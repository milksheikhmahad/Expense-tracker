import { useEffect, useState } from 'react';
import { api } from '../api';

export default function Insights() {
  const [data, setData] = useState(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);

  const load = () => {
    setLoading(true);
    setError('');
    api.insights().then(setData).catch((e) => setError(e.message)).finally(() => setLoading(false));
  };
  useEffect(load, []);

  return (
    <div className="stack">
      <div className="row-between">
        <h1>Insights</h1>
        <button className="ghost" onClick={load} disabled={loading}>{loading ? 'Thinking…' : 'Refresh'}</button>
      </div>
      {error && <div className="error">{error}</div>}
      {data && (
        <div className="card">
          <div className="muted small">
            {data.source === 'azure-openai' ? 'Generated by Azure OpenAI from your aggregated monthly totals (no descriptions or personal details are sent).' : 'Generated from rules over your monthly totals. Configure Azure OpenAI to get AI-written insights.'}
          </div>
          <ul className="insights">
            {data.insights.map((s, i) => <li key={i}>{s}</li>)}
          </ul>
        </div>
      )}
    </div>
  );
}
